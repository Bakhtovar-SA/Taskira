import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const root='D:/CodexScratch/Taskira-UI-Audit-20261009';
const out=`${root}/docs/design/audit-2026-10-09`;
const config=Object.fromEntries(readFileSync(`${root}/server/.env.audit`,'utf8').trim().split(/\r?\n/).map(l=>{const i=l.indexOf('=');return [l.slice(0,i),l.slice(i+1)];}));
mkdirSync(`${out}/screenshots`,{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:900},locale:'ru-RU'});
const page=await context.newPage();
await page.goto('http://localhost:3000',{waitUntil:'networkidle',timeout:60000});
await page.getByLabel('Логин',{exact:true}).fill('audit_admin');
await page.getByLabel('Пароль',{exact:true}).fill(config.AUDIT_USER_PASSWORD);
await page.getByRole('button',{name:'Войти',exact:true}).click();
await page.getByLabel('Логин',{exact:true}).waitFor({state:'hidden',timeout:60000});
await page.waitForTimeout(1500);
await page.screenshot({path:`${out}/screenshots/probe-home.png`});
const inventory=async()=>({url:page.url(),text:(await page.locator('body').innerText()).slice(0,13000),buttons:await page.getByRole('button').evaluateAll(ns=>ns.map(n=>({text:n.innerText,aria:n.getAttribute('aria-label'),title:n.getAttribute('title')}))),inputs:await page.locator('input,textarea').evaluateAll(ns=>ns.map(n=>({tag:n.tagName,placeholder:n.getAttribute('placeholder'),aria:n.getAttribute('aria-label')})))});
const home=await inventory();
await page.goto('http://localhost:3000/p/UX/board',{waitUntil:'networkidle',timeout:60000});await page.locator('[data-issue-id]').first().waitFor();
const board=await inventory();
await page.locator('[data-issue-id]').first().click();await page.getByRole('dialog').waitFor();const issue=await inventory();
await page.keyboard.press('Escape');await page.keyboard.press('c');await page.waitForTimeout(500);const create=await inventory();
writeFileSync(`${out}/browser-inventory.json`,JSON.stringify({home,board,issue,create},null,2));
console.log(JSON.stringify({home:home.url,board:board.url,dialogs:await page.getByRole('dialog').count(),inventory:`${out}/browser-inventory.json`}));
await context.close();await browser.close();
