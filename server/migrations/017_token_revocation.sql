-- 017: отзыв выданных токенов.
--
-- Проблема (аудит SEC-01): «Выйти» удаляло токен только из браузера. Сам JWT
-- оставался валидным до истечения срока (12 часов), и скопированный или
-- перехваченный токен продолжал работать после выхода. Списка отзыва не было.
--
-- Решение без новой таблицы и без похода в БД на каждый запрос: отметка времени
-- на пользователе. Всё, что выдано РАНЬШЕ неё, считается недействительным.
-- Проверка идёт в requireAuth рядом с уже существующим чтением global_role /
-- is_active и попадает в тот же 30-секундный кэш — лишних запросов нет.
--
-- Отметка обновляется при выходе и должна обновляться при любой смене пароля
-- или принудительном завершении сессий администратором.
--
-- NULL — токены не отзывались ни разу (обычное состояние).

ALTER TABLE users ADD COLUMN IF NOT EXISTS tokens_valid_from timestamptz NULL;

COMMENT ON COLUMN users.tokens_valid_from IS
  'Токены, выданные до этого момента, недействительны (выход, смена пароля). NULL — не отзывались.';
