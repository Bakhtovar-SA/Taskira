-- ============================================================
-- Taskira. Миграция 028: почтовые уведомления больше нельзя выключить.
-- Применяется server/src/db.ts migrate() целиком в одной транзакции.
--
-- notify_prefs.email больше не принимает 'off' на уровне контракта
-- (NotifyPrefsBody в contract.ts сужен до 'instant'|'daily') — по запросу:
-- почтовые уведомления обязательны, пользователь выбирает только режим
-- (сразу / дайджест). Бэкфилл существующих 'off' → 'daily' (дайджест, не
-- 'instant' — для тех, кто раньше сознательно всё выключил, дайджест раз
-- в день менее навязчив, чем письмо на каждое событие).
--
-- Строковый литерал 'off' в notify.ts/notifier.ts после этой миграции не
-- становится мёртвым кодом: он остаётся внутренним состоянием "у
-- пользователя нет email" (mode = u.notify_prefs?.email ?? (u.email ?
-- "instant" : "off")) — эта колонка сама по себе не трогается.
-- ============================================================

UPDATE users
   SET notify_prefs = jsonb_set(notify_prefs, '{email}', '"daily"')
 WHERE notify_prefs ->> 'email' = 'off';
