-- ТЗ 4.3 (план v2, Трек 4): «активное место» (seat) под лицензию (см. docs/LICENSE_KEYS.md,
-- server/src/services/license.ts) должно считаться по логинившимся за последние N дней, не по
-- count(*) от users — у AD-дерева с LDAP JIT-провижинингом (routes/auth.ts provisionFromLdap)
-- строка в users появляется при первом входе И при фоновом ресинке департаментов, без участия
-- покупателя; посчитать все строки means первый же клиент с деревом на несколько тысяч человек
-- пробивает лимит мест на старте автоматически, даже если реально работает малая доля.
--
-- Раньше такого столбца не было: единственный сигнал о входах — audit_log (auth.login), но он
-- периодически чистится (AUDIT_RETENTION_DAYS, по умолчанию 365 — больше окна лицензии, но это
-- конфигурируемо и может быть уменьшено ниже окна лицензии без каких-либо предупреждений об
-- этой связи) — считать seats по нему означало бы, что смена ретеншена аудита тихо меняет то,
-- сколько мест лицензия считает занятыми. last_login_at — отдельный операционный столбец на
-- users, тем же duck typing, что failed_login_attempts/locked_until уже используют, обновляется
-- в том же месте (routes/auth.ts), что и они.
--
-- Аддитивная миграция: nullable-колонка (NULL — ни разу не логинился, ожидаемо для только что
-- засеянного/провижненного пользователя), обычный индекс — запрос "последние N дней" range-scan.
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at timestamptz;
CREATE INDEX IF NOT EXISTS idx_users_last_login_at ON users (last_login_at);
