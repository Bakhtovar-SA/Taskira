-- ============================================================
-- Taskira. Миграция 021: подзадачи (issues.parent_id).
-- Применяется server/src/db.ts migrate() целиком в одной транзакции.
--
-- МОДЕЛЬ: подзадача — обычная строка issues с parent_id, указывающим на
--   родителя. Ровно ДВА уровня, без произвольной вложенности — сервер
--   (routes/issues.ts) отказывает и в «подзадаче подзадачи» (parent_id
--   цели должен быть NULL), и в превращении задачи, у которой уже есть
--   свои подзадачи, в чью-то подзадачу. Список подзадач родителя НЕ
--   отдельный запрос: клиент уже грузит весь активный список задач
--   проекта и фильтрует по parentId локально (как уже делает для
--   epicId/«направлений» в TimelineView) — отдельного эндпоинта/сервиса
--   под это заводить не стали.
--
--   Это НЕ то же самое, что epic_id («направление» — свободная группировка
--   без ограничения глубины и без обратной связи со статусом выполнения):
--   подзадача — конкретная дочерняя единица работы у конкретного родителя.
--   Обе колонки независимы, задача может одновременно входить в направление
--   И быть чьей-то подзадачей.
--
-- КАСКАД: удаление родителя НЕ утаскивает подзадачи (ON DELETE SET NULL,
--   как epic_id) — подзадача становится обычной самостоятельной задачей,
--   а не исчезает молча вместе с контекстом, который её породил.
-- Обратима: ALTER TABLE issues DROP COLUMN parent_id.
-- ============================================================

ALTER TABLE issues ADD COLUMN parent_id uuid REFERENCES issues(id) ON DELETE SET NULL;

ALTER TABLE issues ADD CONSTRAINT issues_parent_not_self CHECK (parent_id <> id);

CREATE INDEX idx_issues_parent ON issues (parent_id) WHERE parent_id IS NOT NULL;
