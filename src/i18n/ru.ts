/** Русский словарь — источник истины для ключей (см. en.ts, index.tsx).
 *  Он собран из двух частей, чтобы первый экран не качал строки экранов, которые он не показывает:
 *   - `ruCore.ts` — ключи, которые используют модули стартового графа (то, что `main.tsx` импортирует статически);
 *   - `ruLazy.ts` — всё остальное; грузится отдельным чанком (`loadRuLazy()` в `index.tsx`) и гарантированно
 *     приходит раньше любого ленивого экрана (`lazyView()`), см. `ruSplit.test.ts`.
 *  Новый ключ кладите туда, где его читает код: стартовый модуль — в `ruCore.ts`, ленивый — в `ruLazy.ts`;
 *  `ruSplit.test.ts` проверяет, что стартовый код не использует ключи из `ruLazy.ts`.
 *  Этот модуль нужен тестам и типам (`TKey`, `Dict`); в стартовый код его не импортируют.
 *  Итоговый тип фиксирует множество ключей: en.ts типизирован как Record<keyof Dict, string>, так что
 *  несовпадение ключей — ошибка компиляции, а не молчаливый пропуск строки в одном из языков. */
import ruCore from "./ruCore";
import ruLazy from "./ruLazy";

const ru = { ...ruCore, ...ruLazy } as const;

export default ru;
export type Dict = typeof ru;
export type TKey = keyof Dict;
