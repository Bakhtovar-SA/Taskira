/**
 * ТЗ 2.4: документация, которую можно породить из кода, порождается скриптом (а не поддерживается руками):
 *   docs/MIGRATION-LIST.md — список миграций (имя файла + первая содержательная строка комментария);
 *   docs/API-SCHEMAS.md    — справочник форм запросов и ответов из zod-схем server/src/contract.ts.
 * Таблица прав — отдельный генератор (scripts/generate-permissions.mjs, ТЗ 2.2).
 *
 *   npm run docs:generate   — записать файлы
 *   npm run docs:check      — упасть (код 1), если файлы не совпадают с кодом (CI, джоба `types`)
 *
 * Запускается через tsx из server/node_modules (contract.ts — TypeScript). Вывод детерминирован: без дат и git.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const norm = (s: string) => s.replace(/\r\n/g, "\n");

/* ---------------- миграции ---------------- */
function migrationList(): string {
  const dir = join(root, "server", "migrations");
  const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
  const summary = (file: string): string => {
    const lines = norm(readFileSync(join(dir, file), "utf8")).split("\n");
    const parts: string[] = [];
    for (const raw of lines) {
      if (!raw.trim()) {
        if (parts.length > 0) break; // пустая строка после описания — конец абзаца
        continue; // пустые строки до описания не считаем концом шапки
      }
      if (!raw.trim().startsWith("--")) break; // пошёл SQL — шапка кончилась
      const l = raw.replace(/^\s*--+\s?/, "").trim();
      const decoration = !l || /^=+$/.test(l) || /^-+$/.test(l);
      // служебные директивы docs/MIGRATIONS.md (`-- migration-transaction: none`, `-- recovery: …`) и шапка db.ts — не описание
      const directive = /^(migration-transaction|recovery)\s*:/i.test(l) || /^Применяется server\/src\/db\.ts/i.test(l);
      if (parts.length === 0) {
        if (decoration || directive) continue; // ещё не дошли до описания
        parts.push(l.replace(/^Taskira\.\s*/i, ""));
      } else {
        if (decoration || directive) break; // описание — до пустой строки комментария
        parts.push(l);
      }
    }
    const text = parts.join(" ").replace(/\\/g, "\\\\").replace(/\|/g, "\\|");
    return text.length > 300 ? `${text.slice(0, 297)}…` : text;
  };
  const legacy = files.filter((f) => /^\d{3}_/.test(f));
  const stamped = files.filter((f) => !/^\d{3}_/.test(f));
  const rows = (fs: string[]) => fs.map((f) => `| \`${f}\` | ${summary(f) || "(нет комментария-описания)"} |`).join("\n");
  return `<!-- GENERATED by scripts/generate-docs.ts from server/migrations/*.sql — DO NOT EDIT. -->
# Список миграций

Порождается скриптом (\`npm run docs:generate\`), руками не редактируется. Правила написания миграций — в
[MIGRATIONS.md](./MIGRATIONS.md): исторические \`001\`–\`029\` неизменяемы, новые файлы — с префиксом-меткой времени.

## Исторические (последовательные)

| Файл | Первая строка описания |
|---|---|
${rows(legacy)}

## С меткой времени

| Файл | Первая строка описания |
|---|---|
${rows(stamped)}
`;
}

/* ---------------- zod → markdown ---------------- */
type Def = { type: string; [k: string]: unknown };
const defOf = (s: unknown): Def => (s as { _zod: { def: Def } })._zod.def;
type Check = { check?: string; format?: string; minimum?: number; maximum?: number; length?: number; value?: number; inclusive?: boolean };
const checksOf = (d: Def): Check[] => ((d.checks as { _zod?: { def: Check }; def?: Check }[] | undefined) ?? [])
  .map((c) => c._zod?.def ?? c.def ?? {});

function describe(schema: unknown): { type: string; optional: boolean; nullable: boolean; note: string } {
  let s: any = schema;
  let optional = false;
  let nullable = false;
  const notes: string[] = [];
  for (let i = 0; i < 12; i++) {
    const d = defOf(s);
    if (d.type === "optional") { optional = true; s = d.innerType; continue; }
    if (d.type === "nullable") { nullable = true; s = d.innerType; continue; }
    if (d.type === "default") { optional = true; notes.push(`по умолчанию ${JSON.stringify(d.defaultValue)}`); s = d.innerType; continue; }
    if (d.type === "pipe" && defOf(d.out).type === "transform") { s = d.in; continue; }
    if (d.type === "readonly") { s = d.innerType; continue; }
    break;
  }
  const d = defOf(s);
  let type: string;
  switch (d.type) {
    case "string": {
      type = "string";
      const c = checksOf(d);
      const min = c.find((x) => x.check === "min_length")?.minimum;
      const max = c.find((x) => x.check === "max_length")?.maximum;
      const kinds = [d.format, ...c.map((x) => x.format)].filter((k) => ["uuid", "guid", "email", "datetime", "url"].includes(String(k)))
        .map((k) => k === "guid" ? "uuid" : k);
      if (kinds.length) type = `string (${kinds.join(", ")})`;
      if (min !== undefined || max !== undefined) notes.push(`длина ${min ?? 0}…${max ?? "∞"}`);
      break;
    }
    case "number": {
      type = "number";
      const c = checksOf(d);
      if (c.some((x) => x.check === "number_format" && x.format === "safeint")) type = "integer";
      const min = c.find((x) => x.check === "greater_than" && x.inclusive)?.value;
      const max = c.find((x) => x.check === "less_than" && x.inclusive)?.value;
      if (min !== undefined || max !== undefined) notes.push(`${min ?? "−∞"}…${max ?? "∞"}`);
      break;
    }
    case "boolean": type = "boolean"; break;
    case "enum": type = `enum: ${Object.values(d.entries as Record<string, string>).map((v) => `\`${v}\``).join(" \\| ")}`; break;
    case "literal": type = `\`${JSON.stringify((d.values as unknown[])[0])}\``; break;
    case "array": {
      type = `array&lt;${describe(d.element).type}&gt;`;
      const c = checksOf(d);
      const min = c.find((x) => x.check === "min_length")?.minimum;
      const max = c.find((x) => x.check === "max_length")?.maximum;
      const exact = c.find((x) => x.check === "length_equals")?.length;
      if (exact !== undefined) notes.push(`ровно ${exact} эл.`);
      else if (min !== undefined || max !== undefined) notes.push(`${min ?? 0}…${max ?? "∞"} эл.`);
      break;
    }
    case "record": type = `record&lt;string, ${describe(d.valueType).type}&gt;`; break;
    case "union": {
      const options = d.options as unknown[];
      if (d.discriminator) {
        const field = String(d.discriminator);
        const variants = options.map((o) => {
          const tag = objectShape(o)?.[field];
          return tag ? describe(tag).type : describe(o).type;
        });
        type = `union (${field}: ${variants.join(" \\| ")})`;
      } else {
        type = options.map((o) => describe(o).type).join(" \\| ");
      }
      break;
    }
    case "pipe": type = "pipeline"; break;
    case "object": type = "object"; break;
    case "any": case "unknown": type = "any"; break;
    default: type = d.type;
  }
  return { type, optional, nullable, note: notes.join("; ") };
}

function objectShape(schema: unknown): Record<string, unknown> | null {
  let s: any = schema;
  for (let i = 0; i < 12; i++) {
    const d = defOf(s);
    if (d.type === "object") return (s as { shape: Record<string, unknown> }).shape;
    if (d.type === "pipe") { s = d.in; continue; }
    if (d.type === "optional" || d.type === "nullable" || d.type === "default") { s = d.innerType; continue; }
    return null;
  }
  return null;
}

async function apiSchemas(): Promise<string> {
  const mod = (await import(pathToFileURL(join(root, "server", "src", "contract.ts")).href)) as Record<string, unknown>;
  const isZod = (v: unknown): boolean => typeof v === "object" && v !== null && "_zod" in (v as object) && typeof (v as { safeParse?: unknown }).safeParse === "function";
  const names = Object.keys(mod).filter((k) => isZod(mod[k])).sort();
  // Запрос — то, что клиент шлёт: суффиксы Body/Query/Params (так названы все схемы запросов в contract.ts). Всё остальное —
  // форма данных ответа (…Dto, IssueListPageMeta, SafeUser, ReportRow и т. п.): по умолчанию «ответ», а не «запрос», чтобы
  // странно названная схема не попадала в запросы молча.
  const kindOf = (n: string) => (/(Body|Query|Params)$/.test(n) ? "request" : "response");
  const section = (n: string): string => {
    const shape = objectShape(mod[n]);
    if (!shape) {
      const type = describe(mod[n]).type;
      return `### ${n}\n\n${type.includes("`") ? type : `\`${type}\``}\n`;
    }
    const rows = Object.entries(shape).map(([field, sch]) => {
      const d = describe(sch);
      const flags = [d.optional ? "необязательное" : "", d.nullable ? "может быть null" : ""].filter(Boolean).join(", ");
      return `| \`${field}\` | ${d.type} | ${[flags, d.note].filter(Boolean).join("; ")} |`;
    });
    return `### ${n}\n\n| Поле | Тип | Замечания |\n|---|---|---|\n${rows.join("\n")}\n`;
  };
  const req = names.filter((n) => kindOf(n) === "request");
  const res = names.filter((n) => kindOf(n) === "response");
  return `<!-- GENERATED by scripts/generate-docs.ts from server/src/contract.ts — DO NOT EDIT. -->
# Справочник схем API

Порождается из zod-схем \`server/src/contract.ts\` (\`npm run docs:generate\`), руками не редактируется. Это формы
**данных** (тела и параметры запросов, типы ответов), а не список эндпоинтов и не рантайм-гарантия соответствия ответов
БД: схемы ответов — источник типов клиента и сервера, \`.parse()\` на границе не выполняется (см. CLAUDE.md, ТЗ 2.1).
Точный список маршрутов и их прав — в \`server/README.md\` и \`server/src/routes/\`.

## Запросы (тела, query, params)

${req.map(section).join("\n")}
## Ответы

${res.map(section).join("\n")}`;
}

const outputs: [string, string][] = [
  ["docs/MIGRATION-LIST.md", migrationList()],
  ["docs/API-SCHEMAS.md", await apiSchemas()],
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(([p, c]) => !existsSync(join(root, p)) || norm(readFileSync(join(root, p), "utf8")) !== c);
  if (stale.length) {
    process.stderr.write(`Порождаемая документация устарела: ${stale.map(([p]) => p).join(", ")}.\nЗапустите: npm run docs:generate\n`);
    process.exit(1);
  }
  console.log("docs: ok");
} else {
  for (const [p, c] of outputs) writeFileSync(join(root, p), c);
  console.log(`docs: записано ${outputs.length} файла`);
}
